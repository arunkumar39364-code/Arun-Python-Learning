# Variables and Data Types
# Learning about different types of data in Python

# String (text)
name = "arun"
city = "tokyo"

# Integer (whole number)
age = 28
year = 2026

# Float (decimal number)
height = 1.75
salary = 400000

# Boolean (True or False)
is_engineer = True
is_student = False

# Print the variables
print("Name:", name)
print("City:", city)
print("Age:", age)
print("Year:", year)
print("Height:", height)
print("Salary:", salary)
print("Engineer?", is_engineer)
print("Student?", is_student)

# Math with variables
work_start_year = 2022
experience_years = year - work_start_year
print("Experience years:", experience_years)

# Combine strings
full_info = name + " lives in " + city
print(full_info)